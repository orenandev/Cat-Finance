export type LinguagemExemplo = 'curl' | 'javascript' | 'discord'

export function gerarExemplos(urlBase: string): Record<LinguagemExemplo, string> {
  const curl = [
    `curl -X POST "${urlBase}/lancamentos/texto" \\`,
    `  -H "x-api-key: $CATFINANCE_API_KEY" \\`,
    `  -H "content-type: application/json" \\`,
    `  -d '{"texto": "gastei 42,90 no mercado ontem"}'`,
    '',
    `curl -X POST "${urlBase}/lancamentos" \\`,
    `  -H "x-api-key: $CATFINANCE_API_KEY" \\`,
    `  -H "content-type: application/json" \\`,
    `  -d '{"tipo": "receita", "valor": 1500, "descricao": "Projeto entregue", "data": "2026-10-16"}'`,
    '',
    `curl "${urlBase}/resumo?inicio=2026-10-01&fim=2026-10-31" \\`,
    `  -H "x-api-key: $CATFINANCE_API_KEY"`,
  ].join('\n')

  const javascript = [
    `const api = '${urlBase}'`,
    '',
    'export async function registrar(texto) {',
    '  const resposta = await fetch(`${api}/lancamentos/texto`, {',
    "    method: 'POST',",
    '    headers: {',
    "      'x-api-key': process.env.CATFINANCE_API_KEY,",
    "      'content-type': 'application/json',",
    '    },',
    '    body: JSON.stringify({ texto }),',
    '  })',
    '',
    '  const corpo = await resposta.json()',
    '  if (!resposta.ok) throw new Error(corpo.erro.mensagem)',
    '  return corpo.dados',
    '}',
  ].join('\n')

  const discord = [
    'import {',
    '  Client,',
    '  ContainerBuilder,',
    '  GatewayIntentBits,',
    '  MessageFlags,',
    '  SeparatorBuilder,',
    '  SeparatorSpacingSize,',
    '  TextDisplayBuilder,',
    "} from 'discord.js'",
    '',
    `const api = '${urlBase}'`,
    'const cliente = new Client({ intents: [GatewayIntentBits.Guilds] })',
    "const moeda = new Intl.NumberFormat('pt-BR', { style: 'currency', currency: 'BRL' })",
    '',
    'function montarResposta(sucesso, titulo, linhas) {',
    '  return new ContainerBuilder()',
    '    .setAccentColor(sucesso ? 0x0f9f6e : 0xe23b3b)',
    '    .addTextDisplayComponents(new TextDisplayBuilder().setContent(`### ${titulo}`))',
    '    .addSeparatorComponents(new SeparatorBuilder().setSpacing(SeparatorSpacingSize.Small))',
    "    .addTextDisplayComponents(new TextDisplayBuilder().setContent(linhas.join('\\n')))",
    '}',
    '',
    "cliente.on('interactionCreate', async (interacao) => {",
    "  if (!interacao.isChatInputCommand() || interacao.commandName !== 'gasto') return",
    '  await interacao.deferReply({ flags: MessageFlags.Ephemeral })',
    '',
    '  try {',
    '    const resposta = await fetch(`${api}/lancamentos/texto`, {',
    "      method: 'POST',",
    '      headers: {',
    "        'x-api-key': process.env.CATFINANCE_API_KEY,",
    "        'content-type': 'application/json',",
    '      },',
    "      body: JSON.stringify({ texto: interacao.options.getString('texto', true) }),",
    '      signal: AbortSignal.timeout(8000),',
    '    })',
    '    const corpo = await resposta.json()',
    '',
    '    const container = resposta.ok',
    "      ? montarResposta(true, 'Lançamento registrado', [",
    '          `**${corpo.dados.descricao}**`,',
    "          `${corpo.dados.tipo === 'receita' ? 'Entrada' : 'Saída'} de ${moeda.format(corpo.dados.valor)}`,",
    '          `-# ${corpo.dados.data}`,',
    '        ])',
    "      : montarResposta(false, 'Não consegui registrar', [corpo.erro?.mensagem ?? 'Erro desconhecido'])",
    '',
    '    await interacao.editReply({ components: [container], flags: MessageFlags.IsComponentsV2 })',
    '  } catch {',
    '    await interacao.editReply({',
    "      components: [montarResposta(false, 'Catfinance indisponível', ['Tente novamente em instantes.'])],",
    '      flags: MessageFlags.IsComponentsV2,',
    '    })',
    '  }',
    '})',
    '',
    'cliente.login(process.env.DISCORD_TOKEN)',
  ].join('\n')

  return { curl, javascript, discord }
}

